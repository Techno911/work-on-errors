import { extractRequisitesFromText } from './requisites-extract';

// Синтетический исполнитель — значения фиктивные, держат только формат реквизитов.
process.env.EXECUTOR_INNS = '123456789012';
process.env.EXECUTOR_NAME_PATTERN = 'Исполнителев\\s+Иван';
process.env.EXECUTOR_ADDRESS_PATTERN = 'Выдуманный\\s+переул';

/**
 * Фикстуры — типовые формулировки договоров и счетов. Все значения (имена, ИНН, адреса,
 * счета, телефоны) вымышленные и согласованы с env-фильтром исполнителя выше.
 */

const EXECUTOR_BLOCK =
  'Исполнителев Иван Иванович, паспорт 0000 000000, выдан 01.01.2020 отделом УФМС России по Примерному краю ' +
  'в Примерном районе Примерска, действующий как физическое лицо с применением налогового режима ' +
  '«налог на профессиональный доход», далее именуемый «Исполнитель», с одной стороны, и ';

// Договор внедрения 7.0, преамбула + раздел 12 «Реквизиты сторон» (структура клиента).
const CONTRACT_IP =
  EXECUTOR_BLOCK +
  'Индивидуальный предприниматель Лесников Пётр Андреевич, ИНН 987654321098, ОГРНИП 312345678900015, ' +
  'адрес: 614000, г. Выдуманск, ул. Синтетическая 2-5, (далее – «Заказчик»), действующий на ' +
  'основании свидетельства о государственной регистрации, с другой стороны, именуемые в дальнейшем при ' +
  'совместном упоминании «Стороны», заключили настоящий договор.\n' +
  '12. РЕКВИЗИТЫ СТОРОН:\nИСПОЛНИТЕЛЬ ЗАКАЗЧИК\n' +
  'Исполнителев Иван Иванович ИНН 123456789012\nАдрес: Примерск, Выдуманный переулок, 1-1\n' +
  'Паспорт 0000 000000, выдан 01.01.2020 УФМС России по Примерному краю +79000000000\n' +
  'Банковские реквизиты:\nр/с 40702810000000000001 АО «ТБанк»\nБИК 044525974\n' +
  'ИП Лесников Пётр Андреевич ИНН 987654321098\nОГРНИП 312345678900015\n' +
  'Адрес: 614000, г. Выдуманск, ул. Синтетическая 2-5\n' +
  'Банковские реквизиты:\nр/с 40702810000000000002 ПАО Сбербанк\nБИК 044442607';

// Счёт-договор, юрлицо: полная форма наименования капсом, английские кавычки.
const INVOICE_OOO =
  'СЧЕТ № 25 от 13 января 2026 г.\nИсполнитель:\nИсполнителев Иван Иванович\nИНН: 123456789012\n' +
  'Адрес: Примерск, Выдуманный переулок, 1-1\nТелефон: +79000000000\nБанк: АО «ТБанк»\n' +
  'P/c: 40702810000000000001\nБИК: 044525974\n' +
  'Заказчик:\nОБЩЕСТВО С ОГРАНИЧЕННОЙ ОТВЕТСТВЕННОСТЬЮ “ПРИМЕР ПЛЮС”\n' +
  'Юридический адрес организации: 614001, Россия, г. Выдуманск, ул. Условная, д. 3, пом. 10\n' +
  'ИНН: 5047000000\nКПП: 504700001\nОГРН: 1145000000646\nБанк: АО “Т-Банк”\n' +
  'P/c: 40702810000000000003\nК/с: 30101810145250000974\nБИК: 044525974\n' +
  'Основание: Договор № 18 от 12 декабря 2025 г.';

// Счёт-договор, ИП без адреса в документе и с 15-значным ОГРН, подписанным как «ОГРН».
const INVOICE_IP_NO_ADDRESS =
  'СЧЕТ № 23 от 13 января 2026 г.\nИсполнитель:\nИсполнителев Иван Иванович\nИНН: 123456789012\n' +
  'Адрес: Примерск, Выдуманный переулок, 1-1\nБанк: АО «ТБанк»\nБИК: 044525974\n' +
  'Заказчик:\nИндивидуальный Предприниматель Воробьёв Антон Павлович\n' +
  'ИНН: 507800000024\nОГРН: 315500000000713\nБанк: Филиал "ЦЕНТРАЛЬНЫЙ" Банка ВТБ ПАО Г. МОСКВА\n' +
  'P/c: 40702810000000000004';

describe('extractRequisitesFromText', () => {
  describe('договор с ИП (структура договора внедрения)', () => {
    const r = extractRequisitesFromText(CONTRACT_IP);

    it('берёт адрес заказчика без хвоста «(далее – «Заказчик»)»', () => {
      expect(r.address).toBe('614000, г. Выдуманск, ул. Синтетическая 2-5');
    });

    it('берёт наименование, ИНН и ОГРНИП заказчика', () => {
      expect(r.legalName).toBe('Индивидуальный предприниматель Лесников Пётр Андреевич');
      expect(r.inn).toBe('987654321098');
      expect(r.ogrn).toBe('312345678900015');
    });

    it('у ИП не выдумывает КПП', () => {
      expect(r.kpp).toBeUndefined();
    });
  });

  describe('счёт-договор с юрлицом', () => {
    const r = extractRequisitesFromText(INVOICE_OOO);

    it('распознаёт полную форму наименования и приводит кавычки к «ёлочкам»', () => {
      expect(r.legalName).toBe('ОБЩЕСТВО С ОГРАНИЧЕННОЙ ОТВЕТСТВЕННОСТЬЮ «ПРИМЕР ПЛЮС»');
    });

    it('берёт юридический адрес заказчика, а не исполнителя', () => {
      expect(r.address).toBe('614001, Россия, г. Выдуманск, ул. Условная, д. 3, пом. 10');
    });

    it('берёт ИНН, КПП и ОГРН юрлица', () => {
      expect(r.inn).toBe('5047000000');
      expect(r.kpp).toBe('504700001');
      expect(r.ogrn).toBe('1145000000646');
    });
  });

  describe('счёт-договор с ИП без адреса заказчика', () => {
    const r = extractRequisitesFromText(INVOICE_IP_NO_ADDRESS);

    it('оставляет адрес пустым, а не подставляет адрес исполнителя', () => {
      expect(r.address).toBeUndefined();
    });

    it('берёт 15-значный ОГРНИП целиком, даже когда он подписан «ОГРН»', () => {
      expect(r.ogrn).toBe('315500000000713');
    });

    it('распознаёт ИП с нестандартным регистром', () => {
      expect(r.legalName).toBe('Индивидуальный Предприниматель Воробьёв Антон Павлович');
      expect(r.inn).toBe('507800000024');
    });
  });

  describe('инварианты (проверяются на всех документах разом)', () => {
    const all = [CONTRACT_IP, INVOICE_OOO, INVOICE_IP_NO_ADDRESS].map(extractRequisitesFromText);

    it('никогда не отдаёт реквизиты исполнителя', () => {
      for (const r of all) {
        expect(r.inn).not.toBe('123456789012');
        expect(JSON.stringify(r)).not.toMatch(/Исполнителев|Выдуманный/i);
      }
    });

    it('в значениях нет клаузул договора и висячих скобок', () => {
      for (const r of all) {
        for (const v of Object.values(r)) {
          expect(String(v)).not.toMatch(/далее|именуем|действующ|в лице|сторон/i);
          expect(String(v)).not.toMatch(/[(«][^)»]*$/);
          expect(String(v)).not.toMatch(/^[\s,;:.–—-]|[\s,;:–—-]$/);
        }
      }
    });
  });

  describe('нераспознаваемые документы', () => {
    it('пустой текст (скан без текстового слоя) — пустой результат', () => {
      expect(extractRequisitesFromText('')).toEqual({});
    });

    it('документ только с нашими реквизитами — пустой результат, а не наши данные', () => {
      expect(extractRequisitesFromText(EXECUTOR_BLOCK + 'ИНН 123456789012 Адрес: Примерск, Выдуманный переулок, 1-1')).toEqual({});
    });
  });
});
