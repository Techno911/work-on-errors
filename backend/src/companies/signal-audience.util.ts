import { Company } from './entities/company.entity';

/**
 * Кому вообще позволено писать. Один источник правды для всех сторожей.
 *
 * До 09.08.2026 каждый планировщик решал это сам, и решения разъехались: свод здоровья,
 * сторож доступов и проверка каналов исключали закрытые и демонстрационные компании, а
 * ежедневный дайджест РОПу и пятничная эскалация долга не исключали ничего. Закрытый
 * одного клиента с 36 неразобранными записями продолжал числиться адресатом ежедневного
 * напоминания: не выстрелило только потому, что каналы у него пусты, а у демонстрационной
 * «Аудит Чарли» рабочий чат подключён, то есть заряжено было.
 *
 * Различие между двумя функциями намеренное и повторяет правило жизненного цикла:
 * пауза приглушает то, что мы шлём КОМАНДЕ клиента, и ничего не приглушает из того,
 * что мы шлём себе. Из наблюдения выпасть нельзя ни в одном состоянии.
 */

/** Работа завершена или её никогда не было: адресатов на той стороне нет. */
function isArchivedOrSandbox(company: Company): boolean {
  return company.status === 'closed' || company.status === 'demo';
}

/**
 * Можно ли слать сигнал КОМАНДЕ клиента (РОПу, владельцу, в рабочий чат).
 * Пауза приглушает: требовать работы от команды, которая официально остановлена,
 * значит приучать её игнорировать наши сообщения.
 */
export function canSignalClient(company: Company): boolean {
  if (isArchivedOrSandbox(company)) return false;
  if (company.status === 'paused') return false;
  // Приостановка за неоплату: команда физически не может работать, платформа закрыта. Слать
  // ей напоминания «сдайте запись» и еженедельные отчёты значит требовать невозможного и
  // приучать людей игнорировать наши сообщения. Наблюдение за компанией при этом остаётся.
  if (company.paymentHold) return false;
  return true;
}

/**
 * Нужно ли держать компанию в НАШЕМ наблюдении (своды, журнал, тревоги трекеру).
 * Пауза здесь остаётся: именно так клиента простоял 111 дней невидимым.
 */
export function isUnderOurWatch(company: Company): boolean {
  return !isArchivedOrSandbox(company);
}
