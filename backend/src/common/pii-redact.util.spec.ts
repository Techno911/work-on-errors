import { redactPii } from './pii-redact.util';

describe('redactPii', () => {
  it('скрывает телефон в разных форматах', () => {
    expect(redactPii('Клиент оставил номер +7 912 345 67 89')).toBe('Клиент оставил номер [телефон]');
    expect(redactPii('Позвонить на 8(912)345-67-89')).toBe('Позвонить на [телефон]');
  });

  it('скрывает email', () => {
    expect(redactPii('Написал на ivan.petrov@example.invalid')).toBe('Написал на [email]');
  });

  it('скрывает обращение по имени-отчеству', () => {
    expect(redactPii('Менеджер сказал: Иван Петрович, добрый день')).toBe(
      'Менеджер сказал: [имя клиента], добрый день',
    );
  });

  it('скрывает номер карты', () => {
    expect(redactPii('Оплатил картой 4276 1234 5678 9012')).toBe('Оплатил картой [номер карты]');
  });

  it('не трогает обычный текст без ПДн', () => {
    const text = 'Клиент спросил про цену, менеджер не назвал вилку и клиент ушёл думать';
    expect(redactPii(text)).toBe(text);
  });

  it('пустая строка остаётся пустой', () => {
    expect(redactPii('')).toBe('');
  });

  // Падежи: в разборе отчество почти всегда косвенное, и первая редакция регулярки их не знала.
  it.each([
    ['творительный', 'Разговор с Мариной Сергеевной о переносе.', 'Сергеевной'],
    ['дательный', 'Передал Ивану Петровичу документы.', 'Петровичу'],
    ['винительный', 'Записал Марину Сергеевну на приём.', 'Сергеевну'],
    ['предложный', 'Договорились об Анне Ивановне позже.', 'Ивановне'],
    ['именительный', 'Иван Петрович подтвердил.', 'Петрович'],
  ])('отчество в косвенном падеже скрыто: %s', (_p, text, form) => {
    const out = redactPii(text);
    expect(out).not.toContain(form);
    expect(out).toContain('[имя клиента]');
  });

  it('обычный текст с двумя словами с большой буквы не трогаем', () => {
    const text = 'Компания Рога Копыта прислала счёт.';
    expect(redactPii(text)).toBe(text);
  });

  // Живой случай с прода: «я Ирина Геннадьевна Тержайкина» оставлял фамилию на виду.
  it('фамилия после отчества уходит вместе с именем', () => {
    const out = redactPii('я Ирина Геннадьевна Тержайкина. Хочу услышать про свет.');
    expect(out).not.toContain('Тержайкина');
    expect(out).toContain('[имя клиента]');
    expect(out).toContain('Хочу услышать про свет.');
  });

  it('следующее предложение не съедается', () => {
    const out = redactPii('Иван Петрович. Москва встретила дождём.');
    expect(out).toContain('Москва встретила дождём.');
  });
});
