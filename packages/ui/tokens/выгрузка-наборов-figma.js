// Выгрузка габаритов наборов библиотеки «ЧиП · Оболочка платформ» (файл 2PtSVLWHgzsZx07kSV5jhO).
// Запускается целиком как код инструмента use_figma в этом файле, только читает; результат
// сохраняется в tokens/figma-наборы.json без правок руками. Сверяет его gate/паритет-figma.py:
// состояние взаимодействия (наведение, нажатие, отключено, выбрано) не меняет размер варианта.
// Зачем: 24.09.2026 варианты одного набора расходились по габаритам, и это не ловил ни один замок.
//
// Берутся только наборы со свойством «Состояние» и группы, где состояний больше одного: правило
// касается их. Формат компактный, потому что ответ use_figma обрезается на 20 КБ. «Контроль» это
// FNV-1a от JSON.stringify(наборы): замок пересчитывает его, и правка файла руками роняет проверку.
//
// {
//   "файл": "2PtSVLWHgzsZx07kSV5jhO",
//   "наборы": [
//     { "набор": "Кнопка", "ключ": "…", "страница": "15 Компоненты пакета",
//       "группы": { "Вид=Основная, Размер=md": { "Обычное": "96×44", "Наведение": "96×44" } } }
//   ],
//   "контроль": "5f1c…"
// }
// Группа — остальные свойства варианта; внутри неё значения «Состояния» и габарит «ширина×высота».

const СОСТОЯНИЕ = /^(Состояние|State)$/i;
const число = (x) => String(Math.round(x * 100) / 100);
const наборы = [];
for (const страница of figma.root.children) {
  await страница.loadAsync();
  for (const набор of страница.findAllWithCriteria({ types: ['COMPONENT_SET'] })) {
    const группы = {};
    let естьСостояние = false;
    for (const вариант of набор.children) {
      if (вариант.type !== 'COMPONENT') continue;
      const свойства = вариант.variantProperties || {};
      const ключСостояния = Object.keys(свойства).find((к) => СОСТОЯНИЕ.test(к));
      if (!ключСостояния) continue;
      естьСостояние = true;
      const группа = Object.keys(свойства).filter((к) => к !== ключСостояния).sort()
        .map((к) => `${к}=${свойства[к]}`).join(', ') || '—';
      (группы[группа] = группы[группа] || {})[свойства[ключСостояния]] = `${число(вариант.width)}×${число(вариант.height)}`;
    }
    for (const г of Object.keys(группы)) if (Object.keys(группы[г]).length < 2) delete группы[г];
    if (естьСостояние && Object.keys(группы).length) наборы.push({ набор: набор.name, ключ: набор.key, страница: страница.name, группы });
  }
}
наборы.sort((a, b) => (a.страница + '/' + a.набор).localeCompare(b.страница + '/' + b.набор));
const строка = JSON.stringify(наборы);
let h = 0x811c9dc5;
for (let i = 0; i < строка.length; i++) { h ^= строка.charCodeAt(i); h = Math.imul(h, 0x01000193) >>> 0; }
return { файл: figma.fileKey, наборы, контроль: h.toString(16).padStart(8, '0') };
