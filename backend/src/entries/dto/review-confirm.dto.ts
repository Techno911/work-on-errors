import { IsISO8601, IsOptional, IsString, Matches } from 'class-validator';

/**
 * Подтверждение чтения разбора: клиент возвращает reviewTextHash той версии,
 * которую фактически прочитал (эхо из сериализации записи; автор хеша — сервер).
 * Любой другой формат — 400, любое иное значение — 409 «перечитайте».
 */
export class ReviewConfirmDto {
  @IsString()
  @Matches(/^[0-9a-f]{64}$/)
  expectedHash!: string;

  /**
   * CAS против технического повтора: значение reviewRereadAt, которое клиент
   * сейчас показывает (эхо из сериализации), null до первого подтверждения.
   * Совпадение предиката → факт двигается; расхождение → отдаём текущее
   * авторитетное состояние 200 без нового штампа (ретрай ≠ новое чтение).
   */
  @IsOptional()
  @IsISO8601()
  lastSeenRereadAt?: string | null;
}
