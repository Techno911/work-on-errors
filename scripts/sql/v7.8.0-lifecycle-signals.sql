-- v7.8.0 — два новых типа уведомления для жизненного цикла клиента.
--
-- Причина (разбор у клиента 05.08.2026): двух менеджеров завели 30 июля, пароли ушли владельцу в
-- переписку, ни один не вошёл, и об этом четыре дня не узнал НИКТО. Выдача доступа и смена
-- состава команды не порождали ни одного события, а все сигналы платформы рождаются только
-- из событий: клиент с нулём активности был невидим 111 дней.
--   access_not_used — доступ выдан, вход не состоялся (РОПу, владельцу, трекеру, суперадмину);
--   team_changed    — сотрудника завели или убрали (владельцу, РОПу, нам).
--
-- synchronize=false на проде значения enum сам не добавляет → нужен ALTER TYPE.
-- ADD VALUE IF NOT EXISTS — PG12+, выполняется вне транзакции (psql per-statement).
ALTER TYPE public.notifications_type_enum ADD VALUE IF NOT EXISTS 'access_not_used';
ALTER TYPE public.notifications_type_enum ADD VALUE IF NOT EXISTS 'team_changed';
