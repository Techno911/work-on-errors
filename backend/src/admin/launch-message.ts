import { escapeTelegramHtml } from '../analytics/telegram.service';

/**
 * Стартовое сообщение команде собирается ЗДЕСЬ ЦЕЛИКОМ — черновик и хвост с доступами.
 *
 * Почему в одном модуле: пока черновик жил на фронте, а хвост на бэке, сообщение писали
 * два автора, и никто не видел его целиком — в чат ушла ссылка на платформу дважды
 * (поймано на проде). Класс ошибки лечится не вычиткой, а тем, что склейка одна.
 * Фронт получает черновик отсюда через API и своей копии не держит.
 */

export const PLATFORM_URL = process.env.APP_URL || 'https://app.example.invalid';

// Черновик kick-off: трекер правит под клиента перед отправкой. Человеческий тон, без
// коммерческих деталей (даты триала и цены команда клиента видеть не должна). Ссылки на
// платформу здесь нет намеренно: она одна, в хвосте с доступами, рядом с логином.
export const LAUNCH_MESSAGE_DEFAULT = `Коллеги, привет! Запускаем «Работу над ошибками», платформу разбора звонков и переписок команды.

Что делаем на этой неделе:
1. Менеджеры: загрузить первые звонки на платформу и написать к каждому короткий самоанализ.
2. Руководитель отдела продаж: разобрать каждую запись в течение 24 часов.
3. Владельцу в понедельник придёт первый автоматический отчёт о работе команды.

Доступы каждого: ниже в этом сообщении.

Руководителю отдела продаж: на главной странице платформы нажмите «Подключить Telegram», чтобы каждое утро получать список записей, ждущих разбора.`;

export type AccessMember = {
  fullName: string;
  email: string;
  roleLabel: string;
  hasLoggedIn: boolean;
  /**
   * Именная одноразовая ссылка входа (режим отправки, только не входившим). Пароля платформа
   * больше не рассылает: он живёт в переписке дольше, чем нужно, и передаётся через третьи руки
   * (у клиента пароли двух менеджеров ушли владельцу в личный чат и там и остались). По ссылке
   * человек сам задаёт пароль, после чего ссылка гаснет.
   */
  activationUrl?: string;
};

/**
 * Хвост с доступами. Два режима из одного источника, чтобы превью трекеру и то, что уйдёт
 * в чат, не разъехались:
 *  - 'send'    — разметка Telegram, именная ссылка входа;
 *  - 'preview' — без разметки (превью читает человек в карточке), ссылка замаскирована:
 *                она создаётся в момент отправки и живёт трое суток.
 */
export function buildAccessBlock(members: AccessMember[], mode: 'send' | 'preview'): string {
  const esc = (s: string) => (mode === 'send' ? escapeTelegramHtml(s) : s);
  const lines = members.map((m) => {
    if (m.hasLoggedIn) return `${esc(m.fullName)} (${m.roleLabel}): уже на платформе`;
    const link =
      mode === 'send'
        ? escapeTelegramHtml(m.activationUrl ?? '')
        : 'ссылка создастся при отправке';
    return `${esc(m.fullName)} (${m.roleLabel}): ${esc(m.email)} · вход: ${link}`;
  });
  if (!lines.length) return '';
  const title = mode === 'send' ? '<b>Доступы к платформе</b>' : 'Доступы к платформе';

  // Никому не нужна ссылка: вся команда уже входила (перезапуск после простоя, повторный старт).
  // Объяснять в этом случае, как «придумать пароль по своей ссылке», значит обещать то, чего в
  // сообщении нет: люди пойдут искать ссылку, которой им не выдали.
  const nobodyNeedsLink = members.every((m) => m.hasLoggedIn);
  if (nobodyNeedsLink) {
    return (
      `\n\n${title}:\n${lines.join('\n')}` +
      `\n\nВход: ${PLATFORM_URL}, по вашей рабочей почте и паролю.` +
      `\n\nЗабыли пароль: на странице входа есть «Забыли пароль», письмо придёт на вашу почту.`
    );
  }

  return (
    `\n\n${title} (у каждого своя ссылка, чужой она не подойдёт):\n${lines.join('\n')}` +
    `\n\nПо ссылке вы придумаете себе пароль, дальше вход обычный: ${PLATFORM_URL}. Ссылка одноразовая и живёт 3 дня.` +
    // Путь восстановления называем сразу: иначе забывший пароль идёт к владельцу, и тот
    // становится лишним звеном в цепочке ради действия, которое платформа делает сама.
    `\n\nЕсли ссылка не открылась или истекла: на странице входа есть «Забыли пароль», письмо придёт на вашу почту.`
  );
}

/**
 * Гейт клиентских сообщений: ловит дефекты, которые читатель замечает сразу, а автор нет,
 * потому что собирал текст из кусков и целиком не перечитывал. Возвращает список претензий
 * (пустой = чисто). Проверяет то, что можно проверить машиной, а не стиль.
 */
export function findMessageDefects(text: string): string[] {
  const defects: string[] = [];

  const urls = text.match(/https?:\/\/[^\s<>«»,)]+/g) ?? [];
  const urlCounts = new Map<string, number>();
  for (const raw of urls) {
    const url = raw.replace(/[.,;:]+$/, '');
    urlCounts.set(url, (urlCounts.get(url) ?? 0) + 1);
  }
  for (const [url, count] of urlCounts) {
    if (count > 1) defects.push(`ссылка ${url} повторяется ${count} раза в одном сообщении`);
  }

  const seen = new Map<string, number>();
  for (const line of text.split('\n')) {
    const key = line.trim().toLowerCase();
    if (key.length < 15) continue; // короткие строки повторяются законно
    seen.set(key, (seen.get(key) ?? 0) + 1);
  }
  for (const [line, count] of seen) {
    if (count > 1) defects.push(`строка повторяется ${count} раза: «${line.slice(0, 60)}»`);
  }

  return defects;
}
