/** Последняя версия, о которой вообще есть решение. Нужна фронту как «прочитано всё». */
export function latestKnownVersion(): string {
  const versions = [...RELEASES.map(r => r.version), ...Object.keys(SILENT_VERSIONS)];
  return versions.sort(compareVersions).pop() ?? '0.0.0';
}

/** Сравнение X.Y.Z по числам, а не по строке: иначе «7.10.0» окажется меньше «7.9.0». */
export function compareVersions(a: string, b: string): number {
  const pa = a.split('.').map(Number);
  const pb = b.split('.').map(Number);
  for (let i = 0; i < 3; i++) {
    const diff = (pa[i] ?? 0) - (pb[i] ?? 0);
    if (diff !== 0) return diff;
  }
  return 0;
}

/**
 * Что показать человеку: анонсы новее его отметки, адресованные его роли, и только те,
 * где после фильтра по роли остался хоть один слайд.
 */
export function releasesFor(role: string | undefined, seenVersion: string | null): Release[] {
  if (role !== 'manager' && role !== 'reviewer' && role !== 'owner') return [];
  return RELEASES
    .filter(r => r.audience.includes(role))
    .filter(r => seenVersion === null || compareVersions(r.version, seenVersion) > 0)
    .map(r => ({ ...r, slides: slidesFor(r, role) }))
    .filter(r => r.slides.length > 0)
    .sort((a, b) => compareVersions(a.version, b.version));
}

/** Слайды выпуска для конкретной роли. */
export function slidesFor(release: Release, role: ReleaseAudience): ReleaseSlide[] {
  return release.slides.filter(s => !s.audience || s.audience.includes(role));
}
