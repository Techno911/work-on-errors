-- v8.0.0 — «Что нового»: анонс значимых обновлений при входе (06.08.2026).
--
-- users.releases_seen_version — последняя версия платформы, анонс которой человек прочитал.
-- Фронт сравнивает её с реестром анонсов (frontend/src/content/releases.ts) и показывает всё,
-- что вышло позже.
--
-- BACKFILL — главное здесь. Если оставить колонку пустой у действующей команды, при первом же
-- входе каждый получил бы на руки ВСЮ историю релизов сразу. Поэтому всем, кто уже работает,
-- проставляем версию ПЕРЕД первым анонсом (7.9.2): тогда придёт ровно один новый анонс — тот,
-- ради которого механизм и сделан. Backfill одноразовый (WHERE ... IS NULL + отметка о запуске
-- не нужна: повторный прогон не найдёт NULL у тех, кого уже проставили, а новичкам версию
-- ставит сам фронт при закрытии вводного тура).
--
-- Операции идемпотентны (IF NOT EXISTS): деплой гоняет файл на каждом выкате.

ALTER TABLE public.users
  ADD COLUMN IF NOT EXISTS releases_seen_version varchar(16);

-- Действующие пользователи не должны получить историю релизов пачкой.
UPDATE public.users
   SET releases_seen_version = '7.9.2'
 WHERE releases_seen_version IS NULL
   AND last_login_at IS NOT NULL;
